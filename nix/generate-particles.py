"""Generate the particle table for hyperion-minecraft-proto.

`minecraft:particle_type` is the one registry whose entries are not
interchangeable rows. `ParticleTypes.STREAM_CODEC` is a dispatch: a `VarInt`
id, and then whatever that id's own codec writes. 103 of the 125 types write
nothing at all; the other 22 write bodies of thirteen different shapes. Nothing
between the particle and the end of the frame is length-prefixed, so a type
sent with the wrong body does not lose a field, it shifts every byte after it.

That is why this registry is generated here rather than by the general registry
codegen, which emits an id-only enum per registry out of `protocol.json`.
`protocol.json` cannot express this one: `nix/extract-protocol.py` marks
`net.minecraft.core.particles.ParticleTypes#STREAM_CODEC` `unresolved`, because
following a dispatch needs the runtime type. So this script reads the dispatch
table out of the decompiled Java instead, where each `register` call names the
option class beside the particle, and reads each option class's own
`StreamCodec` to learn the body.

The two sources are held together by `particle_ids_match_the_registry` in the
generated file, which checks every id here against
`generated::registry::PARTICLE_TYPE`. That test is the only reason splitting
this registry off the general codegen is safe: without it, two spellings of one
table could drift and nothing would say so.

Anything in the Java this script does not already understand is a hard failure
rather than a skipped entry. A particle silently omitted would encode as some
other particle's id the next time the registry shifted, and a particle whose
body this got wrong would corrupt the rest of the frame. Neither is worth
trading for a run that finishes.
"""

from __future__ import annotations

import argparse
import json
import re
from pathlib import Path

REGISTRY = "minecraft:particle_type"
POSITION_SOURCE_REGISTRY = "minecraft:position_source_type"

# `ParticleTypes.register("name", overrideLimiter)` for a body-less type, and
# `register("name", overrideLimiter, <codec>, <streamCodec>)` for one with
# options. Only the option class matters here; the `codec` half is the JSON
# form, which never reaches the wire.
REGISTER = re.compile(
    r"public static final (?:SimpleParticleType|ParticleType<(?P<option>\w+)>) "
    r"(?P<constant>\w+) = ParticleTypes\.register\("
    r'"(?P<name>[a-z0-9_]+)", (?:true|false)(?P<tail>.*?)\);$'
)

# The stream codec of an option class, either as a static field or as the sole
# `return` of a `streamCodec(...)` factory.
STREAM_CODEC = re.compile(
    r"(?:STREAM_CODEC = |return )(?P<expr>StreamCodec\.composite\(.*"
    r"|ByteBufCodecs\.\w+(?:\(.*?\))?\.map\(.*"
    r"|\w+\.STREAM_CODEC\.map\(.*);$"
)

# A field name out of a getter: `o -> o.color`, `Type::getScale`,
# `Type::target`, or `o -> Float.valueOf(o.roll)`.
GETTER_FIELD = re.compile(r"(?:\.|::)(?:get)?(?P<field>[A-Za-z]\w*)\s*\)?\s*$")

# How each leaf codec is written, as (rust type, writer method, reader method).
# Anything absent is a codec this script has never seen and will not guess at.
PRIMITIVES = {
    # `ByteBufCodecs.INT` is a fixed four-byte big-endian int, not a VarInt.
    "ByteBufCodecs.INT": ("i32", "i32", "i32"),
    "ByteBufCodecs.VAR_INT": ("i32", "var_int", "var_int"),
    "ByteBufCodecs.FLOAT": ("f32", "f32", "f32"),
}

# Codecs whose type already exists in this crate and encodes itself. Written
# unqualified because the generated preamble imports every one of them; a
# qualified path here would leave that import unused and fail the build.
COMPOSITES = {
    "Vec3.STREAM_CODEC": "Vec3",
    "BlockPos.STREAM_CODEC": "BlockPos",
    "PositionSource.STREAM_CODEC": "PositionSource",
    "ItemStackTemplate.STREAM_CODEC": "ItemStackTemplate<'a>",
}

# `ByteBufCodecs.idMapper(<registry>)` is a bare VarInt index into a registry
# the client already has. Only the block state registry appears in a particle.
ID_MAPPERS = {
    "Block.BLOCK_STATE_REGISTRY": "BlockStateId",
}

# Fields whose `int` is a packed colour rather than a number. Vanilla writes
# both through the same `ByteBufCodecs.INT`, so only the name tells them apart,
# and a colour drawn as an integer is only ever noticed on a client.
COLOUR_FIELDS = {"color", "fromColor", "toColor"}

HEADER = """\
// @generated by nix/generate-particles.py from Minecraft {version} (protocol {protocol}).
// Do not edit by hand. Regenerate with: nix run .#sync-minecraft-particles
"""


def snake(name: str) -> str:
    """`arrivalInTicks` -> `arrival_in_ticks`."""
    return re.sub(r"(?<!^)(?=[A-Z])", "_", name).lower()


def pascal(name: str) -> str:
    """`dust_color_transition` -> `DustColorTransition`."""
    return "".join(part.capitalize() for part in name.split("_"))


def split_args(text: str) -> list[str]:
    """Split a Java argument list on its top-level commas.

    A plain `text.split(",")` cuts inside `Either.right((Object)id)` and inside
    every lambda body, and the pieces then read as codecs that do not exist.
    """
    args, depth, start = [], 0, 0
    for index, char in enumerate(text):
        if char in "([":
            depth += 1
        elif char in ")]":
            depth -= 1
        elif char == "," and depth == 0:
            args.append(text[start:index].strip())
            start = index + 1
    args.append(text[start:].strip())
    return [arg for arg in args if arg]


def balanced(text: str, open_at: int) -> str:
    """The contents of the parenthesised group opening at `open_at`."""
    depth = 0
    for index in range(open_at, len(text)):
        if text[index] == "(":
            depth += 1
        elif text[index] == ")":
            depth -= 1
            if depth == 0:
                return text[open_at + 1:index]
    raise SystemExit(f"unbalanced parentheses in {text!r}")


def field_name(getter: str, option: str) -> str:
    """The field a getter reads, as a Rust identifier."""
    match = GETTER_FIELD.search(getter.strip())
    if not match:
        raise SystemExit(
            f"{option}: cannot tell which field {getter!r} reads; teach this "
            "script the shape before letting it name one"
        )
    return snake(match.group("field"))


class Field:
    """One value a particle's option class writes after the type id."""

    def __init__(self, name: str, rust: str, write: str, read: str) -> None:
        self.name = name
        self.rust = rust
        self.write = write
        self.read = read


def leaf(codec: str, name: str, option: str) -> tuple[str, str, str]:
    """The Rust type, write expression and read expression for one codec."""
    codec = codec.strip()
    if codec in PRIMITIVES:
        rust, write, read = PRIMITIVES[codec]
        if name in {snake(field) for field in COLOUR_FIELDS}:
            if write != "i32":
                raise SystemExit(f"{option}: colour field {name} is not an int")
            return ("Argb", "writer.i32({value}.to_bits());", "Argb::from_bits(reader.i32()?)")
        return (rust, f"writer.{write}(*{{value}});", f"reader.{read}()?")
    if codec.startswith("ByteBufCodecs.idMapper("):
        registry = balanced(codec, codec.index("(")).strip()
        if registry not in ID_MAPPERS:
            raise SystemExit(
                f"{option}: idMapper over {registry}, which this script has no "
                "Rust type for; add one to ID_MAPPERS with its wire form"
            )
        rust = ID_MAPPERS[registry]
        # `ByteBufCodecs.idMapper` is `ByteBufCodecs.VAR_INT.map(...)`: a bare
        # index into a registry the client already holds.
        return (rust, "writer.var_int({value}.to_raw());", f"{rust}::from_raw(reader.var_int()?)?")
    for suffix, rust in COMPOSITES.items():
        if codec.endswith(suffix):
            bare = rust.removesuffix("<'a>")
            if bare == "ItemStackTemplate":
                return (rust, "{value}.encode(writer)?;", f"{bare}::decode(reader, nbt)?")
            return (rust, "{value}.encode(writer)?;", f"{bare}::decode(reader)?")
    raise SystemExit(
        f"{option}: {codec!r} is a codec this script has never seen. Read its "
        "Java and add it to PRIMITIVES, COMPOSITES or ID_MAPPERS; guessing at "
        "a body shifts every byte after the particle."
    )


def parse_option(option: str, source: Path) -> list[Field]:
    """The fields an option class writes, read off its own `StreamCodec`."""
    text = source.read_text()
    matches = [STREAM_CODEC.search(line.strip()) for line in text.splitlines()]
    found = [match.group("expr") for match in matches if match]
    if not found:
        raise SystemExit(f"{option}: no stream codec in {source}")
    expr = found[0]

    if expr.startswith("StreamCodec.composite("):
        args = split_args(balanced(expr, expr.index("(")))
        # `composite(codec, getter, codec, getter, ..., constructor)`, so an
        # even count means one of the pairs is not a pair.
        if len(args) % 2 != 1:
            raise SystemExit(f"{option}: composite has {len(args)} arguments, expected an odd count")
        pairs = [(args[i], args[i + 1]) for i in range(0, len(args) - 1, 2)]
    else:
        # `<codec>.map(fromWire, toWire)`: one field, and the second argument
        # is the getter that names it.
        head, _, tail = expr.rpartition(".map(")
        args = split_args(balanced("(" + tail, 0))
        if len(args) != 2:
            raise SystemExit(f"{option}: map has {len(args)} arguments, expected 2")
        pairs = [(head, args[1])]

    fields = []
    for codec, getter in pairs:
        name = field_name(getter, option)
        rust, write, read = leaf(codec, name, option)
        fields.append(Field(name, rust, write, read))
    names = [field.name for field in fields]
    if len(set(names)) != len(names):
        raise SystemExit(f"{option}: two fields named the same: {names}")
    return fields


PREAMBLE = '''
//! Particle types for Minecraft {version}, and the options each one carries.
//!
//! `ParticleTypes.STREAM_CODEC` is `ByteBufCodecs.registry(PARTICLE_TYPE)
//! .dispatch(ParticleOptions::getType, ParticleType::streamCodec)`: a `VarInt`
//! id, then whatever that id's own codec writes. [`Particle`] is that pair as
//! one closed value, so a caller cannot name a type and forget its body.
//!
//! There is no `Particle::from_id`. A type id alone does not say how many
//! bytes follow it, so turning one back into a particle means reading the
//! body, which is [`Particle::decode`]. [`ParticleKind`] is the id on its own,
//! for the cases that really do only want the number or the name.
//!
//! Both enums are closed and neither has an `Unknown` variant. A type this
//! server never sends is also a type whose body length it does not know, and
//! nothing after the particle is length-prefixed, so there is nothing to skip
//! past: the read has to stop rather than resynchronise on the next field.
//!
//! # Why this registry is generated apart from the others
//!
//! The general registry codegen emits one id-only enum per registry out of
//! `protocol.json`, and it deliberately skips `{registry}`. That
//! file cannot express this one: the extractor marks
//! `ParticleTypes#STREAM_CODEC` `unresolved`, because following a dispatch
//! needs the runtime type, so all it carries for particles is the names.
//! `nix/generate-particles.py` reads the dispatch table out of the decompiled
//! Java instead, which is the only place that says which of the 125 entries
//! carry a payload and what shape it is.
//!
//! **Do not re-add `{registry}` to the general codegen.** Two
//! spellings of one registry can drift, and a drifted particle id draws the
//! wrong particle rather than failing. What makes the split safe is
//! `particle_ids_match_the_registry` below, which holds every id here against
//! `generated::registry::PARTICLE_TYPE`.

use crate::{{
    Decode, Encode, Error, Reader, Result, Writer,
    item::{{ItemStackTemplate, nbt::NbtScan}},
    types::{{BlockPos, BlockStateId, Vec3}},
}};

/// A packed ARGB colour, as a particle option carries it.
///
/// Vanilla writes this through the same `ByteBufCodecs.INT` it writes a count
/// with, so only the field name distinguishes the two in the Java. Giving it a
/// type here is what stops a caller passing a particle count where a colour
/// goes, which is a mistake only a client ever sees.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub struct Argb(i32);

impl Argb {{
    /// A colour from its four channels.
    #[must_use]
    pub const fn new(alpha: u8, red: u8, green: u8, blue: u8) -> Self {{
        Self(
            ((alpha as i32) << 24)
                | ((red as i32) << 16)
                | ((green as i32) << 8)
                | (blue as i32),
        )
    }}

    /// A fully opaque colour.
    #[must_use]
    pub const fn opaque(red: u8, green: u8, blue: u8) -> Self {{
        Self::new(0xff, red, green, blue)
    }}

    /// The packed value exactly as the wire holds it.
    #[must_use]
    pub const fn from_bits(bits: i32) -> Self {{
        Self(bits)
    }}

    /// The packed value exactly as the wire holds it.
    #[must_use]
    pub const fn to_bits(self) -> i32 {{
        self.0
    }}

    /// Alpha, red, green, blue.
    ///
    /// Big-endian bytes rather than shifts: the wire writes this `int` big
    /// endian, so the byte order already is the channel order.
    #[must_use]
    pub const fn channels(self) -> [u8; 4] {{
        self.0.to_be_bytes()
    }}
}}
'''

POSITION_SOURCE = '''
/// Where a vibration is travelling to (`PositionSource`).
///
/// Another registry dispatch, over `{registry}`, which has exactly
/// the two entries below. A third would land here as a build failure in
/// `nix/generate-particles.py` rather than as a wrong body on the wire.
#[derive(Debug, Clone, Copy, PartialEq)]
#[repr(u16)]
pub enum PositionSource {{
{variants}}}

impl PositionSource {{
    /// The `{registry}` id this variant is dispatched on.
    #[must_use]
    pub const fn id(&self) -> u16 {{
        match self {{
{ids}        }}
    }}
}}

impl Encode for PositionSource {{
    fn encode(&self, writer: &mut Writer) -> Result<()> {{
        writer.var_int(i32::from(self.id()));
        match self {{
{encode}        }}
        Ok(())
    }}
}}

impl Decode<'_> for PositionSource {{
    fn decode(reader: &mut Reader<'_>) -> Result<Self> {{
        let id = reader.var_int()?;
        match id {{
{decode}            value => Err(Error::InvalidEnum {{
                name: "PositionSource",
                value,
            }}),
        }}
    }}
}}
'''


