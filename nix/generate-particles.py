def emit(entries, particles, version, protocol, position_sources) -> str:
    """The whole generated file."""
    text = HEADER.format(version=version["id"], protocol=version["protocolVersion"])
    text += PREAMBLE.format(version=version["id"], registry=REGISTRY)
    text += position_sources

    # --- ParticleKind, the id on its own -----------------------------------
    text += """
/// A particle type, without its options.
///
/// The discriminant is the `minecraft:particle_type` id, so [`id`](Self::id)
/// is a move rather than a table lookup. Registry ids are positional and shift
/// whenever Mojang inserts a type, which is why they are generated rather than
/// written down.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
#[repr(u16)]
pub enum ParticleKind {
"""
    for index, particle in enumerate(particles):
        text += f"    /// `{entries[index]}`.\n"
        text += f"    {particle['variant']} = {index},\n"
    text += "}\n"

    text += "\nimpl ParticleKind {\n    /// Every type, in id order, so the index is the id.\n"
    text += "    pub const ALL: &'static [Self] = &[\n"
    text += "".join(f"        Self::{p['variant']},\n" for p in particles)
    text += "    ];\n"
    text += """
    /// The `minecraft:particle_type` id.
    #[must_use]
    pub const fn id(self) -> u16 {
        self as u16
    }

    /// The namespaced registry name, e.g. `minecraft:flame`.
    #[must_use]
    pub const fn name(self) -> &'static str {
        PARTICLE_NAMES[self as usize]
    }

    /// The type an id off the wire names, if this version has one.
    ///
    /// The decode boundary and nowhere else: a type named in source goes
    /// through the variant, so a version that drops it fails to build.
    #[must_use]
    pub const fn from_id(id: u16) -> Option<Self> {
        match id {
"""
    for index, particle in enumerate(particles):
        text += f"            {index} => Some(Self::{particle['variant']}),\n"
    text += """            _ => None,
        }
    }

    /// The type of that namespaced name, if this version has one.
    #[must_use]
    pub fn from_name(name: &str) -> Option<Self> {
        // A scan rather than a map: the table is small and this runs when a
        // name arrives from outside, not per tick.
        let index = PARTICLE_NAMES.iter().position(|entry| *entry == name)?;
        Self::from_id(u16::try_from(index).ok()?)
    }
}

/// Every registry name, in id order.
"""
    text += f"static PARTICLE_NAMES: [&str; {len(entries)}] = [\n"
    text += "".join(f'    "{name}",\n' for name in entries)
    text += "];\n"
    return text


def emit_particle(entries, particles) -> str:
    """The payload enum: a type together with whatever its codec writes."""
    text = """
/// A particle type together with the options its own codec writes.
///
/// One value rather than a type beside a body, because the two are not
/// independent: the id decides how many bytes follow, and nothing after them
/// is length-prefixed. A `Dust` sent without its colour and scale does not
/// draw a colourless dust, it desynchronises the rest of the frame.
#[derive(Debug, Clone, PartialEq)]
#[repr(u16)]
pub enum Particle<'a> {
"""
    for index, particle in enumerate(particles):
        note = (
            f"a `{particle['option']}`." if particle["option"] else "no options."
        )
        text += f"    /// `{entries[index]}`, {note}\n"
        if particle["fields"]:
            text += f"    {particle['variant']} {{\n"
            for field in particle["fields"]:
                text += f"        /// `{particle['option']}.{field.name}`.\n"
                text += f"        {field.name}: {field.rust},\n"
            text += f"    }} = {index},\n"
        else:
            text += f"    {particle['variant']} = {index},\n"
    text += "}\n"

    # --- kind / id / name --------------------------------------------------
    text += """
impl Particle<'_> {
    /// The type, without its options.
    #[must_use]
    pub const fn kind(&self) -> ParticleKind {
        match self {
"""
    for particle in particles:
        pattern = f"Self::{particle['variant']}"
        if particle["fields"]:
            pattern += " { .. }"
        text += f"            {pattern} => ParticleKind::{particle['variant']},\n"
    text += """        }
    }

    /// The `minecraft:particle_type` id.
    #[must_use]
    pub const fn id(&self) -> u16 {
        self.kind().id()
    }

    /// The namespaced registry name, e.g. `minecraft:flame`.
    #[must_use]
    pub const fn name(&self) -> &'static str {
        self.kind().name()
    }
}
"""

    # --- Encode ------------------------------------------------------------
    bare = [p for p in particles if not p["fields"]]
    text += """
impl Encode for Particle<'_> {
    fn encode(&self, writer: &mut Writer) -> Result<()> {
        writer.var_int(i32::from(self.id()));
        match self {
"""
    if bare:
        arms = "\n            | ".join(f"Self::{p['variant']}" for p in bare)
        text += f"            {arms} => {{}}\n"
    # Grouped by option class, because several particles share one class and so
    # write an identical body, and two identical match arms are a lint.
    grouped: dict[str, list[dict]] = {}
    for particle in particles:
        if particle["fields"]:
            grouped.setdefault(particle["option"], []).append(particle)
    for group in grouped.values():
        fields = group[0]["fields"]
        names = ", ".join(field.name for field in fields)
        arms = "\n            | ".join(
            f"Self::{particle['variant']} {{ {names} }}" for particle in group
        )
        text += f"            {arms} => {{\n"
        for field in fields:
            text += "                " + field.write.format(value=field.name) + "\n"
        text += "            }\n"
    text += """        }
        Ok(())
    }
}
"""

    # --- decode ------------------------------------------------------------
    text += """
impl<'a> Particle<'a> {
    /// Read a particle and whatever its type's codec wrote after the id.
    ///
    /// Not a [`Decode`] impl, because one variant carries an item stack and a
    /// stack's component values can only be measured with an NBT scanner. Same
    /// shape as [`crate::packets::play::SetEquipment::decode`], for the same
    /// reason.
    ///
    /// # Errors
    /// [`Error::InvalidEnum`] for a type this version does not have. There is
    /// no recovery from that: the id is what says how long the body is, so an
    /// unknown one leaves nothing to skip.
    pub fn decode(reader: &mut Reader<'a>, nbt: &impl NbtScan) -> Result<Self> {
        let id = reader.var_int()?;
        match id {
"""
    for index, particle in enumerate(particles):
        if not particle["fields"]:
            text += f"            {index} => Ok(Self::{particle['variant']}),\n"
            continue
        text += f"            {index} => Ok(Self::{particle['variant']} {{\n"
        for field in particle["fields"]:
            text += f"                {field.name}: {field.read},\n"
        text += "            }),\n"
    text += """            value => Err(Error::InvalidEnum {
                name: "Particle",
                value,
            }),
        }
    }
}
"""
    text += TESTS.format(count=len(entries))
    return text


def find_class(sources: Path, name: str) -> Path:
    """The one decompiled source file for a Java class."""
    found = sorted(sources.rglob(f"{name}.java"))
    if len(found) != 1:
        raise SystemExit(
            f"{name}.java matched {len(found)} files under {sources}; the "
            "decompiled subset changed and this script is reading the wrong one"
        )
    return found[0]


def emit_position_source(sources: Path, entries: list[str]) -> str:
    """The `PositionSource` dispatch, from the two classes the registry names."""
    known = {"minecraft:block": "BlockPositionSource", "minecraft:entity": "EntityPositionSource"}
    if entries != list(known):
        raise SystemExit(
            f"{POSITION_SOURCE_REGISTRY} is {entries}, not {list(known)}; a "
            "vibration's body changed shape and this script cannot guess the "
            "new one"
        )
    variants, ids, encode, decode = "", "", "", ""
    for index, (entry, klass) in enumerate(known.items()):
        variant = pascal(entry.removeprefix("minecraft:"))
        fields = parse_option(klass, find_class(sources, klass))
        variants += f"    /// `{entry}` (`{klass}`).\n    {variant} {{\n"
        for field in fields:
            variants += f"        /// `{klass}.{field.name}`.\n"
            variants += f"        {field.name}: {field.rust},\n"
        variants += f"    }} = {index},\n"
        ids += f"            Self::{variant} {{ .. }} => {index},\n"
        names = ", ".join(field.name for field in fields)
        encode += f"            Self::{variant} {{ {names} }} => {{\n"
        for field in fields:
            encode += "                " + field.write.format(value=field.name) + "\n"
        encode += "            }\n"
        decode += f"            {index} => Ok(Self::{variant} {{\n"
        for field in fields:
            decode += f"                {field.name}: {field.read},\n"
        decode += "            }),\n"
    return POSITION_SOURCE.format(
        registry=POSITION_SOURCE_REGISTRY,
        variants=variants,
        ids=ids,
        encode=encode,
        decode=decode,
    )


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--protocol", required=True, type=Path)
    parser.add_argument("--sources", required=True, type=Path)
    parser.add_argument("--out", required=True, type=Path)
    args = parser.parse_args()

    doc = json.loads(args.protocol.read_text())
    registries = doc["registries"]
    for required in (REGISTRY, POSITION_SOURCE_REGISTRY):
        if required not in registries:
            raise SystemExit(f"{args.protocol} has no {required}")
    entries = registries[REGISTRY]["entries"]

    # The registry is the authority on which particles exist and what their ids
    # are; the Java is the authority on what each one writes. Reading the ids
    # off the registry rather than off the declaration order in the Java is
    # what lets the two disagree loudly instead of quietly.
    bodies = {}
    java = find_class(args.sources, "ParticleTypes").read_text()
    for line in java.splitlines():
        match = REGISTER.search(line.strip())
        if not match:
            continue
        name = f"minecraft:{match.group('name')}"
        if name in bodies:
            raise SystemExit(f"{name} is registered twice")
        option = match.group("option")
        bodies[name] = option

    missing = [name for name in entries if name not in bodies]
    if missing:
        raise SystemExit(
            f"{len(missing)} registry entries have no register() call in "
            f"ParticleTypes.java, starting with {missing[:4]}; the regex no "
            "longer matches every declaration"
        )
    extra = [name for name in bodies if name not in entries]
    if extra:
        raise SystemExit(f"ParticleTypes.java registers {extra}, which the registry does not list")

    parsed: dict[str, list[Field]] = {}
    particles = []
    for name in entries:
        option = bodies[name]
        if option is not None and option not in parsed:
            parsed[option] = parse_option(option, find_class(args.sources, option))
        particles.append(
            {
                "variant": pascal(name.removeprefix("minecraft:")),
                "option": option,
                "fields": parsed[option] if option else [],
            }
        )

    variants = [particle["variant"] for particle in particles]
    if len(set(variants)) != len(variants):
        raise SystemExit("two registry entries produce the same variant name")

    # A registry the extractor truncated would emit a short table that compiles
    # and draws the wrong thing. These four are what the effects layer is built
    # on, and one of each body shape, so their absence is the cheapest proof
    # the extraction went wrong.
    for required in ("minecraft:flame", "minecraft:dust", "minecraft:block", "minecraft:item"):
        if required not in entries:
            raise SystemExit(f"{REGISTRY} is missing {required}, so the extraction is wrong")

    position_sources = emit_position_source(
        args.sources, registries[POSITION_SOURCE_REGISTRY]["entries"]
    )
    text = emit(entries, particles, doc["version"], doc["version"], position_sources)
    text += emit_particle(entries, particles)
    args.out.write_text(text)


if __name__ == "__main__":
    main()
